/**
 * 金桔财务体系下的货币性项目（Monetary Item）前缀清单
 *
 * 依据 CAS 19《企业会计准则第19号——外币折算》：货币性项目指企业持有的
 * 货币资金和将以固定或可确定金额收取的资产或偿付的负债。期末必须按即期
 * 汇率折算，差额计入汇兑损益。
 *
 * 注意：本清单基于金桔财务的实际科目编码方案，与国标 2014 准则略有差异：
 *   - 1501/1502/1503 在金桔里是固定资产系（非货币性），不是国标的金融资产
 *   - 1401/1471 等存货类属于非货币性项目，按历史汇率锁定
 *
 * 字段 `isMonetary` 用于标识科目是否参与期末汇兑重估，可由用户在科目
 * 编辑页手动调整。
 */

export const MONETARY_PREFIXES: readonly string[] = [
  // 流动资产（货币资金 + 应收/预付类）
  '1001', // 库存现金
  '1002', // 银行存款
  '1012', // 其他货币资金
  '1101', // 交易性金融资产
  '1121', // 应收票据
  '1122', // 应收账款
  '1123', // 预付账款
  '1131', // 应收股利
  '1132', // 应收利息
  '1221', // 其他应收款
  '1231', // 坏账准备

  // 流动负债
  '2001', // 短期借款
  '2002', // 存入保证金
  '2101', // 交易性金融负债
  '2151', // 应付职工薪酬（金桔自定义编码）
  '2201', // 应付票据
  '2202', // 应付账款
  '2203', // 预收账款
  '2211', // 应付职工薪酬（部分编码）
  '2221', // 应交税费
  '2231', // 应付利息
  '2232', // 应付股利
  '2241', // 其他应付款

  // 非流动负债
  '2501', // 长期借款
  '2502', // 应付债券
  '2701', // 长期应付款
  '2702', // 未确认融资费用
] as const;

/**
 * 根据科目代码推断是否属于货币性项目。
 * 用于新建科目时的默认值推断，用户可在科目编辑页手动调整。
 */
export function inferIsMonetary(code: string | undefined | null): boolean {
  if (!code) return false;
  return MONETARY_PREFIXES.some((p) => code.startsWith(p));
}
